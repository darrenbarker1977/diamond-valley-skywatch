import {test,expect} from '@playwright/test';
test('open, search, select, filter, expand, red mode and close',async({page},testInfo)=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>{window.sensorSubscriptions=[];const original=window.addEventListener;window.addEventListener=function(name,...args){if(['deviceorientation','deviceorientationabsolute','devicemotion'].includes(name))window.sensorSubscriptions.push(name);return original.call(this,name,...args);};});
 await page.clock.setFixedTime(new Date('2026-10-27T03:00:00Z'));
 await page.goto('/prototype/');
 await page.getByRole('button',{name:'Sky Navigator',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await expect(page.locator('#objects button')).toHaveCount(27);
 await page.locator('#search').fill('m 31');
 await expect(page.locator('#objects button')).toHaveCount(1);
 await page.locator('#objects button').click();
 await expect(page.locator('#target-name')).toHaveText('Andromeda Galaxy');
 await expect(page.locator('#detail')).toContainText('TRUE AZIMUTH');
 await page.locator('#search').fill('nothingmatches');
 await expect(page.locator('#count')).toContainText('No matching objects');
 await page.locator('#search').fill('');
 await page.getByRole('button',{name:'Above horizon',exact:true}).click();
 expect(await page.locator('#objects button').count()).toBeGreaterThan(0);
 await expect(page.locator('#objects')).not.toContainText('Below horizon');
 await page.getByRole('button',{name:'Expand panel'}).click();
 await expect(page.locator('#navigator')).toHaveClass(/dv-nav-expanded/);
 await page.getByRole('button',{name:'Red night mode: off'}).click();
 await expect(page.locator('body')).toHaveClass('dv-nav-night');
 await page.waitForTimeout(250);
 await page.locator('#pointing').evaluate(el=>el.open=false);
 await page.locator('#close').scrollIntoViewIfNeeded();
 await page.screenshot({path:`prototype/screenshots/${testInfo.project.name}-night.png`,fullPage:true});
 await page.getByRole('button',{name:'Red night mode: on'}).click();
 await expect(page.locator('body')).not.toHaveClass('dv-nav-night');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await expect(page.locator('#sensor-status')).toHaveText('Sensors off');
 await page.locator('#pointing').evaluate(el=>el.open=false);
 await page.locator('#close').scrollIntoViewIfNeeded();
 await page.waitForTimeout(250);
 await page.screenshot({path:`prototype/screenshots/${testInfo.project.name}.png`,fullPage:true});
 expect(await page.evaluate(()=>window.sensorSubscriptions)).toEqual([]);
 await page.getByRole('button',{name:'Close Navigator'}).click();
 await expect(page.locator('#launch')).toBeFocused();
 await page.locator('#launch').click();await page.keyboard.press('Escape');
 await expect(page.getByRole('dialog')).not.toBeVisible();
 expect(errors).toEqual([]);
});
test('library failure gives an honest error and no positions',async({page})=>{
 await page.route('**/vendor/astronomy.browser.min.js',route=>route.abort());
 await page.goto('/prototype/');await page.locator('#launch').click();
 await expect(page.getByRole('alert')).toContainText('astronomy library did not load');
 await expect(page.locator('#objects button')).toHaveCount(0);
 await expect(page.locator('#detail')).toBeEmpty();
});
test('keyboard stays inside modal and timer retains search focus',async({page})=>{
 await page.clock.install();await page.goto('/prototype/');await page.locator('#launch').click();
 await page.locator('#search').focus();await page.clock.fastForward(11000);
 await expect(page.locator('#search')).toBeFocused();
 await page.locator('#close').focus();await page.keyboard.press('Tab');
 expect(await page.evaluate(()=>document.querySelector('#navigator').contains(document.activeElement))).toBe(true);
});
